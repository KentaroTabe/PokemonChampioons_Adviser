"""画面上の情報領域の定義 (相対座標 0..1) と切り出しユーティリティ。

スクリーンショット (1334x750, iPhone) と OBS 仮想カメラ (1280x720) の両方で
使えるよう、すべて画面幅・高さに対する比率で定義する。
基準は images/ 配下の実機スクリーンショット (16:9)。
"""
from __future__ import annotations


def _z(x0, y0, x1, y1):
    return {"x0": x0, "y0": y0, "x1": x1, "y1": y1}


def crop(img, zone):
    """相対ゾーンで切り出す"""
    h, w = img.shape[:2]
    y0 = max(0, int(zone["y0"] * h))
    y1 = min(h, int(zone["y1"] * h))
    x0 = max(0, int(zone["x0"] * w))
    x1 = min(w, int(zone["x1"] * w))
    if y1 <= y0 or x1 <= x0:
        return None
    return img[y0:y1, x0:x1]


